    action_type TEXT NOT NULL,
    context TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users access own logs" ON public.activity_logs;

CREATE POLICY "Users access own logs" ON public.activity_logs FOR ALL USING (auth.uid() = user_id);

-- 7. GLOBAL LEADERBOARD VIEW
DROP VIEW IF EXISTS public.global_leaderboard;
CREATE OR REPLACE VIEW public.global_leaderboard AS
SELECT 
    p.id,
    p.full_name,
    p.level,
    p.xp,
    p.streak_count,
    ROW_NUMBER() OVER (ORDER BY p.xp DESC) as rank
FROM public.profiles p;

